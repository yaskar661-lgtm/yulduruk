import asyncio
from playwright.async_api import async_playwright

async def get_youtube_cookies():
    async with async_playwright() as p:
        # Gerçek bir tarayıcı başlatıyoruz (bot algılanmasını en aza indirmek için argümanlarla)
        browser = await p.chromium.launch(
            headless=True,
            args=[
                "--disable-blink-features=AutomationControlled",
                "--no-sandbox",
                "--disable-setuid-sandbox"
            ]
        )
        
        # Kullanıcı ajanı (User-Agent) ve gizlilik ayarları
        context = await browser.new_context(
            user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
        )
        
        page = await context.new_page()
        
        print("YouTube'a bağlanılıyor...")
        try:
            # YouTube ana sayfasına git
            await page.goto("https://www.youtube.com", timeout=60000)
            await page.wait_for_timeout(5000) # Sayfanın oturması için bekle
            
            # Tarayıcıdaki çerezleri al
            cookies = await context.cookies()
            
            # Netscape cookies.txt formatına dönüştür
            cookie_lines = ["# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n"]
            for cookie in cookies:
                domain = cookie.get("domain", "")
                flag = "TRUE" if domain.startswith(".") else "FALSE"
                path = cookie.get("path", "/")
                secure = "TRUE" if cookie.get("secure", False) else "FALSE"
                expires = str(int(cookie.get("expires", 0)))
                name = cookie.get("name", "")
                value = cookie.get("value", "")
                
                cookie_lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}\n")
                
            # cookies.txt dosyasına yaz
            with open("cookies.txt", "w", encoding="utf-8") as f:
                f.writelines(cookie_lines)
                
            print("cookies.txt başarıyla oluşturuldu ve güncellendi!")
            
        except Exception as e:
            print(f"Çerez çekerken hata oluştu: {e}")
        finally:
            await browser.close()

if __name__ == "__main__":
    asyncio.run(get_youtube_cookies())
